/**
 * The library shelf's pure layer (/admin/library, founder ask
 * 2026-07-31: "we upload things from homa-inspo but have a hard time
 * seeing, as a human, what has been uploaded, and what the extraction
 * results and metadata are").
 *
 * Three truth layers have to meet here, and none of them points
 * reliably at the others:
 *
 *   1. Analysis JSON in .cosmo/references and .cosmo/curriculums, in
 *      git, written by the reference-ingestion and curriculum-ingestion
 *      skills. This is what was UNDERSTOOD.
 *   2. Original bytes in Blob under inspo/<record-id>/<filename>. This
 *      is what was KEPT. Only 3 of 195 reference JSONs record their own
 *      blobUrl, so the Blob listing is the authority, never the JSON.
 *   3. Cover thumbnails in Blob under inspo-covers/<record-id>.jpg,
 *      generated by scripts/backfill-library-covers.mts. This is what
 *      the shelf can SHOW.
 *
 * A record can exist in any subset of the three, and the gaps are the
 * point of the surface rather than an error to hide: bytes with no
 * analysis mean Cosmo missed a drop, and analysis with no bytes means
 * the original is gone for good. Disk-free on purpose, the same posture
 * as cosmo-funnel.ts, so every rule below is unit-testable.
 */

export type LibraryKind = "reference" | "curriculum";

/** Where the record entered the corpus. Scrapes never had bytes to
 * lose, so they must never be counted as a capture failure. */
export type LibraryOrigin = "slack" | "scrape";

export type ShelfStatus =
  /** Analysis plus the original bytes. The whole record is intact. */
  | "complete"
  /** Analysed, but the original is gone. Expired TeachersPayTeachers
   * and Etsy links land here; the analysis is all that survives. */
  | "original-lost"
  /** Analysed, and the dropper has already been asked for missing source
   * bytes. A partial original can remain while corrupt pages or a later
   * installment are still outstanding. */
  | "awaiting-source"
  /** Analysed, and no original was ever expected (web scrape). */
  | "analysis-only"
  /** Bytes in Blob with no analysis JSON at all. Cosmo missed it.
   * This is the bucket the founders cannot currently see. */
  | "unread";

export interface LibraryBook {
  id: string;
  kind: LibraryKind;
  title: string;
  publisher: string | null;
  series: string | null;
  droppedBy: string;
  /** ISO string, from the Slack message ts, never the machine clock. */
  droppedAt: string | null;
  format: string | null;
  subject: string | null;
  gradeLevel: string | null;
  pageCount: number | null;
  origin: LibraryOrigin;
  status: ShelfStatus;
  /** Public Blob URL of the cover thumbnail, when one was generated. */
  coverUrl: string | null;
  /** Public Blob URL of the original file, when the bytes survive. */
  originalUrl: string | null;
  originalName: string | null;
  /** Size of the primary file shown on the detail page. */
  originalBytes: number | null;
  /** Every unique original retained for this book, primary file first. */
  originalFiles: LibraryOriginalFile[];
  /** Bytes held across every unique original file for this book. */
  totalOriginalBytes: number;
  /** Every extra file kept under the same record id (multi-part scans). */
  extraFileCount: number;
  /** The untouched analysis document, for the detail view's reader.
   * Null for an unread record: there is nothing to show yet. */
  analysis: Record<string, unknown> | null;
}

/** Blob objects the shelf knows about, keyed by record id. */
export interface BlobOriginal {
  recordId: string;
  url: string;
  name: string;
  size: number;
}

export type LibraryOriginalFile = Pick<BlobOriginal, "url" | "name" | "size">;

const SCRAPE_DROPPERS = /atlas|scrape/i;

/** A drop is a scrape when the dropper says so. Founder names (sid,
 * aless, carolyng) always mean a real #homa-inspo upload. */
export function classifyOrigin(droppedBy: string): LibraryOrigin {
  return SCRAPE_DROPPERS.test(droppedBy) ? "scrape" : "slack";
}

/**
 * The shelf's triage rule: what a founder sees first, and what reads as
 * fine. Deliberately ranks "bytes we never read" above "analysis whose
 * bytes are gone", because the first is recoverable work sitting in the
 * corpus right now and the second is already lost.
 */
export function classifyShelfStatus(
  origin: LibraryOrigin,
  hasAnalysis: boolean,
  hasOriginal: boolean,
  originalRecoveryStatus?: unknown,
  sourceCompletenessStatus?: unknown,
): ShelfStatus {
  if (!hasAnalysis) return "unread";
  if (
    sourceCompletenessStatus === "requested" ||
    sourceCompletenessStatus === "awaiting-source"
  ) {
    return "awaiting-source";
  }
  if (hasOriginal) return "complete";
  if (originalRecoveryStatus === "requested") return "awaiting-source";
  return origin === "scrape" ? "analysis-only" : "original-lost";
}

