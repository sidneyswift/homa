/**
 * Subject to cover accent. Designed covers need a stable colour per
 * subject so the shelf reads as a shelf; these are design-system token
 * names, never raw hex (DESIGN.md, no invented colour).
 */
const SUBJECT_ACCENTS: Record<string, string> = {
  math: "clay",
  mathematics: "clay",
  ela: "sky",
  english: "sky",
  "language-arts": "sky",
  reading: "sky",
  science: "sage",
  "social-studies": "gold",
  history: "gold",
  spanish: "rose",
  "world-languages": "rose",
  art: "rose",
  health: "sage",
  multidisciplinary: "stone",
};

export type CoverAccent = "clay" | "sky" | "sage" | "gold" | "rose" | "stone";

const ACCENT_CYCLE: CoverAccent[] = ["clay", "sky", "sage", "gold", "rose", "stone"];

/**
 * The name a designed cover is coloured by when the subject is unknown.
 *
 * Publisher first, then series. Sixty-nine of the scraped records carry
 * neither, but their titles all lead with the publisher ("Oak Meadow 1
 * Beginning Recorder Sample Lesson", "Beast Academy 3A Angle Mazes"),
 * so the first two words stand in. Two words rather than one because
 * "Oak" and "Beast" alone collide with too much.
 */
export function coverLiveryKey(book: {
  publisher: string | null;
  series: string | null;
  title: string;
}): string | null {
  if (book.publisher?.trim()) return book.publisher.trim();
  if (book.series?.trim()) return book.series.trim();
  const words = book.title.trim().split(/\s+/).slice(0, 2);
  return words.length ? words.join(" ") : null;
}

/**
 * Cloth colour for a designed cover.
 *
 * Subject decides it when we know the subject. The 102 scraped records
 * carry no subject at all, though, and defaulting them all to stone
 * produces a hundred identical dark rectangles, which is a wall and not
 * a shelf. So publisher is the fallback: every Oak Meadow sample takes
 * one colour and every Beast Academy sample another, which is both more
 * legible and how a real shelf already works. Hashing keeps it stable
 * across renders, since a cover that changes colour on reload reads as
 * a bug.
 */
export function subjectAccent(subject: string | null, publisher?: string | null): CoverAccent {
  if (subject) {
    const key = subject.trim().toLowerCase().replace(/[\s_]+/g, "-");
    const known = SUBJECT_ACCENTS[key] as CoverAccent | undefined;
    if (known) return known;
  }
  const house = publisher?.trim().toLowerCase();
  if (!house) return "stone";
  let hash = 0;
  for (let index = 0; index < house.length; index += 1) {
    hash = (hash * 31 + house.charCodeAt(index)) % 100_000;
  }
  return ACCENT_CYCLE[hash % ACCENT_CYCLE.length];
}

function firstString(...values: unknown[]): string | null {
  for (const value of values) {
    if (typeof value === "string" && value.trim()) return value.trim();
  }
  return null;
}

function firstNumber(...values: unknown[]): number | null {
  for (const value of values) {
    if (typeof value === "number" && Number.isFinite(value)) return value;
  }
  return null;
}

/** The analysis JSONs disagree about where the subject lives: a
 * reference keeps it under skillTargeting, a curriculum at the top
 * level, and the atlas batch left it blank. Try each in turn. */
function readSubject(raw: Record<string, unknown>): string | null {
  const direct = firstString(raw.subject);
  if (direct) return direct;
  const targeting = raw.skillTargeting;
  if (targeting && typeof targeting === "object") {
    const nested = targeting as Record<string, unknown>;
    const fromTargeting = firstString(nested.subject);
    if (fromTargeting) return fromTargeting;
  }
  const overall = raw.overallSkillTargeting;
  if (overall && typeof overall === "object") {
    return firstString((overall as Record<string, unknown>).subject);
  }
  return null;
}

/**
 * Turn one analysis document into a shelf record. Returns null only
 * when the document has no id, which is the one field every writer in
 * the pipeline sets; anything else missing is shown as a gap rather
 * than dropped, because a half-filled record is exactly what the
 * founders are trying to see.
 */
export function parseLibraryRecord(
  raw: unknown,
  kind: LibraryKind,
): Omit<
  LibraryBook,
  | "status"
  | "coverUrl"
  | "originalUrl"
  | "originalName"
  | "originalBytes"
  | "originalFiles"
  | "totalOriginalBytes"
  | "extraFileCount"
> | null {
  if (!raw || typeof raw !== "object") return null;
  const doc = raw as Record<string, unknown>;
  const id = firstString(doc.id);
  if (!id) return null;

  const droppedBy = firstString(doc.droppedBy) ?? "unknown";
  return {
    id,
    kind,
    title: firstString(doc.title, doc.name) ?? id,
    publisher: firstString(doc.publisher, doc.author, doc.authors),
    series: firstString(doc.series),
    droppedBy,
    droppedAt: firstString(doc.droppedAt),
    format: firstString(doc.format),
    subject: readSubject(doc),
    gradeLevel: firstString(doc.gradeLevel, doc.level),
    pageCount: firstNumber(doc.pageCount, doc.physicalPageCount, doc.pdfScanPageCount),
    origin: classifyOrigin(droppedBy),
    analysis: doc,
  };
}

/**
 * Parse the analysis documents that represent individual retained or
 * retainable files on the admin bookshelf. Catalog-only summaries and
 * analysis-only provenance records remain valid for corpus search, but
 * neither represents a distinct file a founder can open on the shelf.
 */
export function parseLibraryShelfRecords(
  docs: unknown[],
  kind: LibraryKind,
): NonNullable<ReturnType<typeof parseLibraryRecord>>[] {
  const records: NonNullable<ReturnType<typeof parseLibraryRecord>>[] = [];
  for (const doc of docs) {
    const record = parseLibraryRecord(doc, kind);
    if (record) records.push(record);
  }
  return records;
}

function readOriginalRecoveryStatus(analysis: Record<string, unknown> | null): string | null {
  if (!analysis || !analysis.originalRecovery || typeof analysis.originalRecovery !== "object") {
    return null;
  }
  return firstString((analysis.originalRecovery as Record<string, unknown>).status);
}

function readSourceCompletenessStatus(analysis: Record<string, unknown> | null): string | null {
  if (
    !analysis ||
    !analysis.sourceCompleteness ||
    typeof analysis.sourceCompleteness !== "object"
  ) {
    return null;
  }
  return firstString((analysis.sourceCompleteness as Record<string, unknown>).status);
}

/** inspo/<record-id>/<file name>. Anything shallower is not ours. */
export function recordIdFromBlobPath(pathname: string): string | null {
  const parts = pathname.split("/");
  if (parts.length < 3 || parts[0] !== "inspo") return null;
  return parts[1] || null;
}

const HOMA_PUBLIC_BLOB_HOST = "pkvvudjdhxk33dig.public.blob.vercel-storage.com";

function isPinnedHomaBlobUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return (
      url.protocol === "https:" &&
      url.host === HOMA_PUBLIC_BLOB_HOST &&
      url.username === "" &&
      url.password === ""
    );
  } catch {
    return false;
  }
}

/**
 * Exact live Blob objects claimed by each analysis document. A source
 * URL is untrusted corpus text until it equals a URL returned by the
 * current Blob listing and that URL belongs to Homa's pinned store.
 * Keeping this keyed by the complete URL also means one claimed part
 * cannot silently pull unclaimed neighbors from the same directory.
 */
function declaredOriginalOwners(
  records: NonNullable<ReturnType<typeof parseLibraryRecord>>[],
  originals: BlobOriginal[],
): Map<string, Set<string>> {
  const liveUrls = new Set(
    originals.map((original) => original.url).filter(isPinnedHomaBlobUrl),
  );
  const owners = new Map<string, Set<string>>();
  for (const record of records) {
    if (!record.analysis || !Array.isArray(record.analysis.sourceFiles)) continue;
    for (const source of record.analysis.sourceFiles) {
      if (!source || typeof source !== "object") continue;
      const blobUrl = firstString((source as Record<string, unknown>).blobUrl);
      if (!blobUrl || !liveUrls.has(blobUrl)) continue;
      const claimedBy = owners.get(blobUrl) ?? new Set<string>();
      claimedBy.add(record.id);
      owners.set(blobUrl, claimedBy);
    }
  }
  return owners;
}

export function coverPathForRecord(recordId: string): string {
  return `inspo-covers/${recordId}.jpg`;
}

/**
 * The slug a record id and its Blob directory have in common, once the
 * kind prefix and the date are stripped:
 *
 *   ref-2026-07-21-one-potato-two-potato  ->  one-potato-two-potato
 *   drop-2026-07-20-one-potato-two-potato ->  one-potato-two-potato
 *
 * Five uploads landed under a "drop-" prefix instead of "ref-"/"cur-",
 * and one of those also disagrees with its analysis about the date by a
 * day, so an exact id join reports the same book twice: once as bytes
 * nobody read, once as analysis whose file is gone. Both are false.
 */
export function libraryJoinKey(recordId: string): string {
  return recordId
    .replace(/^(ref|cur|drop)-/, "")
    .replace(/^\d{4}-\d{2}-\d{2}-/, "");
}

/**
 * Merge the three layers into one shelf. Records with analysis come
 * first; Blob ids with no analysis are synthesised into "unread" books
 * so the bytes stop being invisible.
 */
/**
 * Collapse the same upload appearing under two Blob directories.
 *
 * Five files were uploaded twice, once under the record's own id and
 * once under a "drop-" prefixed directory, byte for byte identical
 * (same filename, same size). Left alone they read as material nobody
 * ever analysed, which would send a founder off to re-ingest a 133MB
 * book that is already fully analysed. Identity is settled first, on
 * (slug, filename, size), and only then does the join run.
 *
 * The surviving directory is the one a record actually points at, then
 * a canonical ref-/cur- prefix, then whichever sorts first, so the
 * choice never depends on Blob's listing order.
 */
export function dedupeOriginals(
  originals: BlobOriginal[],
  knownRecordIds: Set<string>,
): BlobOriginal[] {
  const groups = new Map<string, BlobOriginal[]>();
  for (const original of originals) {
    const key = `${libraryJoinKey(original.recordId)}::${original.name}::${original.size}`;
    groups.set(key, [...(groups.get(key) ?? []), original]);
  }
  const kept: BlobOriginal[] = [];
  for (const group of groups.values()) {
    if (group.length === 1) {
      kept.push(group[0]);
      continue;
    }
    const ranked = [...group].sort((a, b) => {
      const rank = (o: BlobOriginal) =>
        knownRecordIds.has(o.recordId) ? 0 : /^(ref|cur)-/.test(o.recordId) ? 1 : 2;
      return rank(a) - rank(b) || a.recordId.localeCompare(b.recordId);
    });
    kept.push(ranked[0]);
  }
  return kept;
}

export function buildShelf(
  records: ReturnType<typeof parseLibraryRecord>[],
  originals: BlobOriginal[],
  covers: Map<string, string>,
): LibraryBook[] {
  const parsed = records.filter((record): record is NonNullable<typeof record> => record !== null);
  const isHidden = (record: (typeof parsed)[number]) => {
    const visibility = record.analysis?.libraryVisibility;
    return visibility === "catalog-only" || visibility === "analysis-only";
  };
  // Hidden analyses still own their Blob objects. Keeping them in identity
  // reconciliation prevents those bytes from reappearing as "Never read."
  const hidden = parsed.filter(isHidden);
  const present = parsed.filter((record) => !isHidden(record));
  const knownRecordIds = new Set(
    parsed.map((record) => record.id),
  );
  const declaredOwners = declaredOriginalOwners(parsed, originals);
  const originalsById = new Map<string, BlobOriginal[]>();
  for (const original of dedupeOriginals(originals, knownRecordIds)) {
    const claims = declaredOwners.get(original.url);
    const [claimedOwner] = claims?.size === 1 ? claims : [];
    // A declaration may fold an otherwise orphaned multipart object,
    // but it may never steal bytes from another canonical record.
    const owner =
      claimedOwner &&
      (!knownRecordIds.has(original.recordId) || claimedOwner === original.recordId)
        ? claimedOwner
        : original.recordId;
    const list = originalsById.get(owner) ?? [];
    list.push(original);
    originalsById.set(owner, list);
  }

  /**
   * Reconcile the ids that do not match exactly. Slug alone is not a
   * safe key on its own: the corpus really does hold two distinct
   * five-paragraph-essay-outline references from different days, and
   * merging them would be a silent data error on the one surface whose
   * job is to tell the truth about the corpus. So a slug match is
   * accepted only when exactly one unmatched candidate exists on each
   * side; anything ambiguous stays unmatched and stays visible.
   */
  const unmatchedBlobIds = [...originalsById.keys()].filter(
    (id) => !present.some((record) => record.id === id),
  );
  const unmatchedRecords = parsed.filter((record) => !originalsById.has(record.id));
  const aliasForRecord = new Map<string, string>();
  if (unmatchedBlobIds.length && unmatchedRecords.length) {
    const blobBySlug = new Map<string, string[]>();
    for (const id of unmatchedBlobIds) {
      const slug = libraryJoinKey(id);
      blobBySlug.set(slug, [...(blobBySlug.get(slug) ?? []), id]);
    }
    const recordsBySlug = new Map<string, string[]>();
    for (const record of unmatchedRecords) {
      const slug = libraryJoinKey(record.id);
      recordsBySlug.set(slug, [...(recordsBySlug.get(slug) ?? []), record.id]);
    }
    for (const [slug, blobIds] of blobBySlug) {
      const recordIds = recordsBySlug.get(slug);
      if (blobIds.length === 1 && recordIds?.length === 1) {
        aliasForRecord.set(recordIds[0], blobIds[0]);
      }
    }
  }

  const books: LibraryBook[] = [];
  const seen = new Set<string>(hidden.map((record) => record.id));
  for (const record of hidden) {
    const alias = aliasForRecord.get(record.id);
    if (alias) seen.add(alias);
  }

  for (const record of present) {
    seen.add(record.id);
    const alias = aliasForRecord.get(record.id);
    if (alias) seen.add(alias);
    const files = originalsById.get(record.id) ?? originalsById.get(alias ?? "") ?? [];
    const orderedFiles = [...files].sort(
      (a, b) => b.size - a.size || a.name.localeCompare(b.name) || a.url.localeCompare(b.url),
    );
    // Largest file remains the primary cover source and summary file,
    // while every retained original stays available to the detail UI.
    const primary = orderedFiles[0] ?? null;
    books.push({
      ...record,
      status: classifyShelfStatus(
        record.origin,
        true,
        files.length > 0,
        readOriginalRecoveryStatus(record.analysis),
        readSourceCompletenessStatus(record.analysis),
      ),
      // Covers are keyed by the Blob directory, so an aliased record
      // or folded part id, not necessarily under its own id.
      coverUrl:
        covers.get(record.id) ??
        covers.get(alias ?? "") ??
        orderedFiles.map((file) => covers.get(file.recordId)).find(Boolean) ??
        null,
      originalUrl: primary?.url ?? null,
      originalName: primary?.name ?? null,
      originalBytes: primary?.size ?? null,
      originalFiles: orderedFiles.map(({ url, name, size }) => ({ url, name, size })),
      totalOriginalBytes: orderedFiles.reduce((sum, file) => sum + file.size, 0),
      extraFileCount: Math.max(0, orderedFiles.length - 1),
    });
  }

  for (const [recordId, files] of originalsById) {
    if (seen.has(recordId)) continue;
    const orderedFiles = [...files].sort(
      (a, b) => b.size - a.size || a.name.localeCompare(b.name) || a.url.localeCompare(b.url),
    );
    const primary = orderedFiles[0];
    books.push({
      id: recordId,
      kind: recordId.startsWith("cur-") ? "curriculum" : "reference",
      title: primary.name.replace(/\.[a-z0-9]+$/i, ""),
      publisher: null,
      series: null,
      droppedBy: "unknown",
      droppedAt: dateFromRecordId(recordId),
      format: null,
      subject: null,
      gradeLevel: null,
      pageCount: null,
      origin: "slack",
      status: "unread",
      coverUrl: covers.get(recordId) ?? null,
      originalUrl: primary.url,
      originalName: primary.name,
      originalBytes: primary.size,
      originalFiles: orderedFiles.map(({ url, name, size }) => ({ url, name, size })),
      totalOriginalBytes: orderedFiles.reduce((sum, file) => sum + file.size, 0),
      extraFileCount: Math.max(0, orderedFiles.length - 1),
      analysis: null,
    });
  }

  return books.sort((a, b) => (b.droppedAt ?? "").localeCompare(a.droppedAt ?? ""));
}

/** ref-2026-07-18-slug carries its own drop date; an unread record has
 * no JSON to read one from. */
export function dateFromRecordId(recordId: string): string | null {
  const match = recordId.match(/(\d{4}-\d{2}-\d{2})/);
  return match ? `${match[1]}T00:00:00Z` : null;
}

export interface ShelfCounts {
  total: number;
  byStatus: Record<ShelfStatus, number>;
  /** Bytes we hold across every original. */
  originalBytes: number;
  withCover: number;
  /** Books carrying a to-do, the number the founder is here to see. */
  needsWork: number;
}

export function countShelf(books: LibraryBook[]): ShelfCounts {
  const byStatus: Record<ShelfStatus, number> = {
    unread: 0,
    "original-lost": 0,
    "awaiting-source": 0,
    complete: 0,
    "analysis-only": 0,
  };
  let originalBytes = 0;
  let withCover = 0;
  let work = 0;
  for (const book of books) {
    byStatus[book.status] += 1;
    originalBytes += book.totalOriginalBytes;
    if (book.coverUrl) withCover += 1;
    if (needsWork(book.status)) work += 1;
  }
  return { total: books.length, byStatus, originalBytes, withCover, needsWork: work };
}
