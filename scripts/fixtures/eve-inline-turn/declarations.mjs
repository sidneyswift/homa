const file = join(artifact, 'offline-declaration-proof.ts');
writeFileSync(file, source.replaceAll("from './dist/", "from '" + provenance.candidate + "/dist/"));
const options = { strict: true, noEmit: true, skipLibCheck: true, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, target: ts.ScriptTarget.ES2022 };
const program = ts.createProgram([file], options);
const diagnostics = ts.getPreEmitDiagnostics(program);
const rows = diagnostics.map(d => ({ code: d.code, message: ts.flattenDiagnosticMessageText(d.messageText, ' ') }));
writeFileSync(join(artifact, 'declaration-results.json'), JSON.stringify({ typescriptVersion: ts.version, candidate: provenance.candidate, checked: 'Strict consumer contract against all changed declaration exports; skipLibCheck preserves existing dependency declaration assumptions.', diagnostics: rows, passed: rows.length === 0 }, null, 2) + '\n');
assert.equal(rows.length, 0, JSON.stringify(rows));
console.log(JSON.stringify({ passed: true, typescriptVersion: ts.version }));
