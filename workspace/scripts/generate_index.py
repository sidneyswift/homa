#!/usr/bin/env python3
"""
Generate index.md for the Homeschool Obsidian vault.

Walks the entire vault, classifies every .md file, and produces a current
catalog grouped by purpose. Picks up new files automatically — no
hand-editing needed when Homa adds a new lesson, plan, or research note.

Output: ~/Documents/Homeschool/index.md

Idempotent. Safe to run repeatedly. Called by regenerate_vault.py.
"""

import datetime
import pathlib
import re
from collections import defaultdict

VAULT = pathlib.Path.home() / "Documents" / "Homeschool"

# Top-level files that get pinned at the top
CORE_FILES = ["Home", "Child"]

# Hand-maintained reference files (small section, separate from auto-gen)
HAND_MAINTAINED_FILES = ["Curriculum Overview", "Weekly Schedule", "What Homa Can Do"]

# Folders to walk and how to label them
SECTION_LABELS = {
    "Subjects": "📖 Subjects (auto-generated per domain)",
    "Curriculum": "📚 Curriculum guides (hand-maintained source materials)",
    "Lessons": "📝 Lesson logs (Less's daily reports)",
    "Weekly-Plans": "📅 Weekly plans",
    "Research": "🔬 Research notes (one per night, auto-generated)",
    "Activities": "🎨 Activity ideas",
    "Resources": "🔗 Resources & links",
    "Sources": "📂 Source materials (raw originals)",
    "Templates": "📋 Templates",
    "Progress": "📈 Progress milestones",
    "Daily Log": "🗓️ Daily logs",
}

# Sort orders for specific folders (newest-first, oldest-first, alphabetical)
SORT_NEWEST_FIRST = {"Research", "Lessons", "Weekly-Plans", "Daily Log"}


def relative_link(path: pathlib.Path, label: str = None) -> str:
    """Build an Obsidian wiki-link to a vault-relative path."""
    rel = path.relative_to(VAULT).with_suffix("").as_posix()
    if label is None:
        label = path.stem
    if label != rel:
        return f"[[{rel}|{label}]]"
    return f"[[{rel}]]"


def is_auto_generated(path: pathlib.Path) -> bool:
    """Check first 5 lines for the AUTO-GENERATED banner."""
    try:
        with path.open() as f:
            head = "".join(f.readline() for _ in range(5))
        return "🤖 AUTO-GENERATED" in head
    except Exception:
        return False


def is_hand_maintained(path: pathlib.Path) -> bool:
    """Check first 5 lines for the HAND-MAINTAINED banner."""
    try:
        with path.open() as f:
            head = "".join(f.readline() for _ in range(5))
        return "🖐️ HAND-MAINTAINED" in head
    except Exception:
        return False


def list_md_files(folder: pathlib.Path, recursive: bool = True):
    """List markdown files in a folder, excluding READMEs and stubs."""
    if not folder.exists() or not folder.is_dir():
        return []
    if recursive:
        files = list(folder.rglob("*.md"))
    else:
        files = list(folder.glob("*.md"))
    files = [f for f in files if f.is_file() and f.name != "README.md"]
    return files


def main():
    today = datetime.date.today()

    lines = []
    lines.append("# 📚 Index")
    lines.append("")
    lines.append(f"> 🤖 AUTO-GENERATED — last rebuilt {today.isoformat()}. Source: walking the vault. Don't hand-edit; this is recreated by `scripts/generate_index.py` on every vault regeneration.")
    lines.append("")
    lines.append("Everything in the homeschool vault, current as of the last regeneration.")
    lines.append("")

    # Core (pinned)
    lines.append("## ⭐ Start here")
    lines.append("")
    for name in CORE_FILES:
        f = VAULT / f"{name}.md"
        if f.exists():
            tag = " 🤖" if is_auto_generated(f) else ""
            lines.append(f"- {relative_link(f)}{tag}")
    lines.append("")

    # Subjects (15 auto-gen files, alphabetical by display name)
    subjects_dir = VAULT / "Subjects"
    if subjects_dir.exists():
        files = sorted(list_md_files(subjects_dir, recursive=False))
        if files:
            lines.append(f"## {SECTION_LABELS['Subjects']}")
            lines.append("")
            lines.append("Per-domain breakdowns of the child's position. All auto-generated from `children/*.json`.")
            lines.append("")
            for f in files:
                lines.append(f"- {relative_link(f)}")
            lines.append("")

    # Research (newest first)
    research_dir = VAULT / "Research"
    if research_dir.exists():
        files = sorted(list_md_files(research_dir, recursive=False), key=lambda f: f.stat().st_mtime, reverse=True)
        if files:
            lines.append(f"## {SECTION_LABELS['Research']}")
            lines.append("")
            lines.append("One per night, generated by the Nightly Research cron.")
            lines.append("")
            for f in files[:20]:  # cap at 20 most recent
                lines.append(f"- {relative_link(f)}")
            if len(files) > 20:
                lines.append(f"- _…plus {len(files) - 20} older entries_")
            lines.append("")

    # Weekly Plans (newest first)
    plans_dir = VAULT / "Weekly-Plans"
    if plans_dir.exists():
        files = sorted(list_md_files(plans_dir, recursive=False), key=lambda f: f.stat().st_mtime, reverse=True)
        if files:
            lines.append(f"## {SECTION_LABELS['Weekly-Plans']}")
            lines.append("")
            for f in files[:10]:
                lines.append(f"- {relative_link(f)}")
            if len(files) > 10:
                lines.append(f"- _…plus {len(files) - 10} older plans_")
            lines.append("")

    # Lessons (newest first, recursive — they live in YYYY-MM/ subfolders)
    lessons_dir = VAULT / "Lessons"
    if lessons_dir.exists():
        files = sorted(list_md_files(lessons_dir, recursive=True), key=lambda f: f.stat().st_mtime, reverse=True)
        lines.append(f"## {SECTION_LABELS['Lessons']}")
        lines.append("")
        if files:
            for f in files[:15]:
                lines.append(f"- {relative_link(f)}")
            if len(files) > 15:
                lines.append(f"- _…plus {len(files) - 15} older logs_")
        else:
            lines.append("_No lesson logs yet — Less hasn't reported any lessons through the homeschool-log skill._")
        lines.append("")

    # Curriculum (alphabetical, recursive — they have sub-pages)
    curriculum_dir = VAULT / "Curriculum"
    if curriculum_dir.exists():
        # Top-level curriculum files first
        top = sorted(list_md_files(curriculum_dir, recursive=False))
        # Then sub-curriculum folders
        sub_files = []
        for sub in sorted(curriculum_dir.iterdir()):
            if sub.is_dir():
                sub_files.extend(sorted(list_md_files(sub, recursive=True)))
        if top or sub_files:
            lines.append(f"## {SECTION_LABELS['Curriculum']}")
            lines.append("")
            for f in top:
                lines.append(f"- {relative_link(f)}")
            for f in sub_files:
                # Indent sub-pages
                rel_parts = f.relative_to(curriculum_dir).parts
                indent = "  " * (len(rel_parts) - 1)
                lines.append(f"{indent}- {relative_link(f)}")
            lines.append("")

    # Activities, Resources, Sources, Templates, Progress, Daily Log
    for folder_name in ["Activities", "Resources", "Sources", "Templates", "Progress", "Daily Log"]:
        folder = VAULT / folder_name
        files = list_md_files(folder, recursive=True)
        if files:
            lines.append(f"## {SECTION_LABELS.get(folder_name, folder_name)}")
            lines.append("")
            for f in sorted(files):
                lines.append(f"- {relative_link(f)}")
            lines.append("")
        elif folder.exists():
            # Folder exists but is empty — show that
            lines.append(f"## {SECTION_LABELS.get(folder_name, folder_name)}")
            lines.append("")
            lines.append(f"_(empty)_")
            lines.append("")

    # Hand-maintained reference files
    lines.append("## 🖐️ Hand-maintained reference")
    lines.append("")
    lines.append("These are setup documents that humans update manually.")
    lines.append("")
    for name in HAND_MAINTAINED_FILES:
        f = VAULT / f"{name}.md"
        if f.exists():
            lines.append(f"- {relative_link(f)}")
    lines.append("")

    # System
    lines.append("## 🔧 System")
    lines.append("")
    log_file = VAULT / "log.md"
    if log_file.exists():
        lines.append(f"- {relative_link(log_file, 'log')} — what changed when (auto-generated)")
    lines.append(f"- This file — index of everything (auto-generated)")
    lines.append("")

    # Footer
    lines.append("---")
    lines.append(f"_Regenerated by `scripts/generate_index.py`. Walks {VAULT}._")
    lines.append("")

    out = "\n".join(lines)
    (VAULT / "index.md").write_text(out)
    print(f"Wrote index.md ({len(out)} bytes)")


if __name__ == "__main__":
    main()
